export type IconName = keyof typeof ICONS;

export function Icon({ name, size = 24, color = 'currentColor', stroke = 2.2 }: { name: IconName; size?: number; color?: string; stroke?: number }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke={color}
      strokeWidth={stroke}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      dangerouslySetInnerHTML={{ __html: ICONS[name] }}
    />
  );
}

export function Gremlin({ color, size }: { color: string; size: number }) {
  return <img src={svgDataUri(gremlinSvg(color))} width={size} height={size} alt="" draggable={false} style={{ flex: 'none' }} />;
}

export function Sticker({ code, size }: { code: string; size: number }) {
  return <img src={svgDataUri(stickerSvg(code))} width={size} height={size} alt="" draggable={false} style={{ flex: 'none' }} />;
}

/** Round initial for a parent (no photos for parents in the designs). */
export function Initial({ name, color, size = 56 }: { name: string; color: string; size?: number }) {
  return (
    <span className="initial" style={{ background: color, width: size, height: size }}>
      {name.trim().charAt(0).toUpperCase()}
    </span>
  );
}
